CREATE TABLE IF NOT EXISTS po_line_items (
    po_number         TEXT    NOT NULL,
    sku               TEXT    NOT NULL,
    source_file       TEXT,
    buyer             TEXT,
    ship_terms        TEXT,
    ref_master_po     TEXT,
    ship_date         TEXT,
    vendor            TEXT,
    ship_to           TEXT,
    bill_to           TEXT,
    dept              TEXT,
    upc               TEXT,
    vendor_part_no    TEXT,
    description       TEXT,
    retail            REAL,
    cost              REAL,
    ext_cost          REAL,
    cartons           INTEGER,
    case_pack         INTEGER,
    ext_qty           INTEGER,
    cube              REAL,
    kilograms         REAL,
    total_cost        REAL,
    validation_flags  TEXT,
    loaded_at         TEXT    NOT NULL,
    PRIMARY KEY (po_number, sku)
);
